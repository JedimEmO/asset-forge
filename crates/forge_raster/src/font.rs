/// Columns for `c`, uppercased; unknown characters fall back to a blank.
pub(crate) fn glyph(c: char) -> [u8; GLYPH_W] {
    let upper = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == upper)
        .map_or([0; GLYPH_W], |(_, bits)| *bits)
}

/// Width in pixels of `text` at `scale`.
#[must_use]
pub fn text_width(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        (n * GLYPH_W + (n - 1) * TRACKING) * scale
    }
}
