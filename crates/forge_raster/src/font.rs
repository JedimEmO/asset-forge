//! A 5x7 bitmap font, just big enough to label a contact sheet.
//!
//! Labels are burnt into the composited sheet rather than rendered as Bevy UI
//! into each cell. That keeps this crate free of font assets, UI cameras and
//! text-shaping dependencies — a contact sheet should not need a font file on
//! disk to say "frame 3". Text is uppercased on the way in, so the table only
//! carries one case.

/// Glyph width in pixels, before scaling.
pub(crate) const GLYPH_W: usize = 5;
